'use strict';
/* THE STAY PLAN'S BROWSER COPY: src/stay-plan.js is the one source (an ES module the Worker imports); this writes
 * assets/stay-plan.js — the same code as a plain script that hangs the module on window.SIYL_STAY_PLAN.
 *   node src/build-stay-plan.cjs          # write assets/stay-plan.js
 *   node src/build-stay-plan.cjs --check  # exit 1 if the copy is stale */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'src/stay-plan.js'), 'utf8');
const names = [];
const body = src.replace(/^export (const|function) ([A-Za-z_]+)/gm, (m, kind, name) => { names.push(name); return kind + ' ' + name; });
const js = '/* GENERATED by src/build-stay-plan.cjs from src/stay-plan.js — do not edit here. The one stay plan — the complimentary allocation and its paid extension, for the browser. */\n' +
  '(function () {\n\'use strict\';\n' + body + '\nwindow.SIYL_STAY_PLAN = { ' + names.map((n) => n + ': ' + n).join(', ') + ' };\n})();\n';
const dest = path.join(ROOT, 'assets/stay-plan.js');
if (process.argv.includes('--check')) { const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : ''; if (cur !== js) { console.error('STAY PLAN: assets/stay-plan.js is stale — run node src/build-stay-plan.cjs'); process.exit(1); } console.log('stay plan: current'); process.exit(0); }
fs.writeFileSync(dest, js);
console.log('stay plan: ' + names.length + ' exports → assets/stay-plan.js');
