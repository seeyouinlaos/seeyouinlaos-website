/* ============================================================================
   GENERATOR · src/billing/product-words.js (Owners, 19 Nov 2026 · HS-004.9): the products as the guest knows them, for the statement.
   The names are the WEBSITE'S OWN approved names — read here from the pages' catalogue (assets/rooms-data.js through the same sandbox
   the tests use) and, for the journeys that are not rooms, from assets/journey.js — and written once into a server-side module the Worker
   can import. Nothing is renamed or invented; the sync test (test/product-words.test.mjs) regenerates and compares.
   Usage: node src/build-product-words.mjs
   ========================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { page, PEGGY } from '../test/sandbox.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function productWords() {
  const P = page({ auth: PEGGY }).SIYL_PRICE;
  const out = {};
  /* the rooms: the stay's name and the room's name; the window and its dates as the detail */
  const HOTEL = { 'bkk-stay': 'U Sathorn Bangkok' };   /* the Bangkok stay is named by its window on the site; its hotel is U Sathorn Bangkok */
  for (const win of ['bkk-stay', 'prewed', 'wedstay', 'guesthouse', 'kmg', 'ljg', 'kempinski']) {
    const at = P.locate(win);
    if (!at || !at.stay) continue;
    const stay = HOTEL[win] || at.stay.name;
    for (const r of at.stay.rooms || []) {
      const room = String(r.name || '').trim();
      const same = !room || room.toLowerCase() === String(stay).toLowerCase();
      out[win + '/' + r.slug] = { name: same ? (at.win.bagName || stay) : stay + ' · ' + room, detail: at.win.label + ' · ' + at.win.dates };
    }
  }
  /* the journeys that are not rooms: their label, route and day as the journey page shows them (assets/journey.js) */
  const J = fs.readFileSync(path.join(ROOT, 'assets/journey.js'), 'utf8');
  const entry = (key) => {
    const m = new RegExp("\\{ key: '" + key + "'[^}]*?\\}", 's').exec(J);
    if (!m) return null;
    const f = (k) => { const x = new RegExp(k + ": '([^']*)'").exec(m[0]); return x ? x[1] : ''; };
    return { label: f('label'), title: f('title'), place: f('place'), when: f('when') };
  };
  const YEAR = ' 2027';
  const flat = { train: 'train', mu9646: 'mu9646', c86: 'c86', return: 'return' };
  for (const [key, id] of Object.entries(flat)) {
    const e = entry(id); if (!e) continue;
    out[key] = { name: e.label.includes(e.place) ? e.label : e.label + ' · ' + e.place, detail: e.when.replace('Feb', 'February').replace('Mar', 'March') + YEAR };
  }
  const s = entry('sangkhathan');
  if (s) out.sangkhathan = { name: s.title, detail: 'Wat Ong Teu, Vientiane · 28 February' + YEAR };
  return out;
}

export function moduleText(words) {
  return '/* GENERATED by src/build-product-words.mjs from the website\'s own catalogue (assets/rooms-data.js, assets/journey.js) — do not edit;\n' +
    '   change the website\'s names and run the build. Keyed by Site_Product_Key (002). HS-004.9, Owners 19 Nov 2026. */\n' +
    'export const PRODUCT_WORDS = Object.freeze(' + JSON.stringify(words, null, 1) + ');\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const words = productWords();
  fs.writeFileSync(path.join(ROOT, 'src/billing/product-words.js'), moduleText(words));
  console.log('product words: ' + Object.keys(words).length + ' products → src/billing/product-words.js');
}
