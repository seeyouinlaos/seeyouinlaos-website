/* ============================================================================
   THE STATEMENT PDF'S LOGO (layout 1.3 · Owners, 19 Nov 2026) — written from the approved original, never drawn.

   node src/pdf-brand-build.mjs  →  src/billing/pdf-brand.js

   The Owners' order: the existing, approved "see you in laos." logo with its red final period — no new logo, no change to it. The
   statement writer (src/billing/pdf.js) sets type in the PDF's base-14 fonts only, which cannot set the wordmark's own typeface, so the
   logo enters the PDF as the approved image itself: assets/brand/see-you-in-laos-email.png (the e-mail logo already in production),
   its PNG data inflated and unfiltered here — its own pixels, nothing redrawn, recoloured,
   cropped or scaled. The module records the source's SHA-256; test/settlement-pdf-brand.test.mjs proves the committed module is this
   file's pixels and that the asset is still the one it was built from.
   ========================================================================== */
import fs from 'node:fs';
import crypto from 'node:crypto';
import zlib from 'node:zlib';

const ROOT = new URL('..', import.meta.url).pathname;
const SRC = 'assets/brand/see-you-in-laos-email.png';
const png = fs.readFileSync(ROOT + SRC);
/* the PNG's own pixels: its IDAT inflated and its row filters undone (8-bit RGBA, not interlaced — refused otherwise) */
let o = 8, W = 0, H = 0, depth = 0, type = 0, inter = 0; const idat = [];
while (o + 8 <= png.length) {
  const n = png.readUInt32BE(o), k = png.toString('latin1', o + 4, o + 8);
  if (k === 'IHDR') { W = png.readUInt32BE(o + 8); H = png.readUInt32BE(o + 12); depth = png[o + 16]; type = png[o + 17]; inter = png[o + 20]; }
  if (k === 'IDAT') idat.push(png.subarray(o + 8, o + 8 + n));
  o += 12 + n;
}
if (depth !== 8 || type !== 6 || inter !== 0) throw new Error('the approved logo is not an 8-bit RGBA, non-interlaced PNG');
const raw = zlib.inflateSync(Buffer.concat(idat)), C = 4, st = W * C, px = Buffer.alloc(W * H * C);
const paeth = (a, b, c) => { const p = a + b - c, x = Math.abs(p - a), y = Math.abs(p - b), z = Math.abs(p - c); return x <= y && x <= z ? a : y <= z ? b : c; };
let prev = Buffer.alloc(st);
for (let y = 0; y < H; y++) {
  const f = raw[y * (st + 1)], r = raw.subarray(y * (st + 1) + 1, (y + 1) * (st + 1)), cur = px.subarray(y * st, (y + 1) * st);
  if (f > 4) throw new Error('unknown PNG filter');
  for (let x = 0; x < st; x++) { const a = x >= C ? cur[x - C] : 0, b = prev[x], c = x >= C ? prev[x - C] : 0; cur[x] = (r[x] + [0, a, b, (a + b) >> 1, paeth(a, b, c)][f]) & 255; }
  prev = cur;
}
/* the logo is opaque: its RGB is the logo exactly (a transparent pixel would have to be laid on something — refused instead) */
const rgb = Buffer.alloc(W * H * 3);
for (let i = 0; i < W * H; i++) { if (px[i * 4 + 3] !== 255) throw new Error('the approved logo is not opaque'); rgb[i * 3] = px[i * 4]; rgb[i * 3 + 1] = px[i * 4 + 1]; rgb[i * 3 + 2] = px[i * 4 + 2]; }
/* compressed ONCE, here: the writer embeds these fixed bytes as they are (/FlateDecode), so no compressor runs in the Worker and the same
   statement always gives the same PDF bytes */
const data = zlib.deflateSync(rgb, { level: 9 });
const paper = [rgb[0], rgb[1], rgb[2]];
const sha = crypto.createHash('sha256').update(png).digest('hex');
const pixelSha = crypto.createHash('sha256').update(rgb).digest('hex');
const out = `/* GENERATED by src/pdf-brand-build.mjs from ${SRC} (sha256 ${sha}) — do not edit by hand.
   The approved "see you in laos." logo with its red final period, as the statement PDF embeds it (layout 1.3 · Owners, 19 Nov 2026):
   the original's own pixels (RGB, ${W} × ${H}, opaque), compressed once at build time (/FlateDecode), and the paper colour of its
   background (its top-left pixel), on which the PDF lays it. */
export const BRAND_SOURCE = Object.freeze({ path: '${SRC}', sha256: '${sha}', pixelSha256: '${pixelSha}' });
export const BRAND_PAPER_RGB = Object.freeze([${paper.join(', ')}]);
const B64 = '${data.toString('base64')}';
const bytes = (s) => { const bin = atob(s); const u = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i); return u; };
export const BRAND_LOGO = Object.freeze({ width: ${W}, height: ${H}, colorSpace: 'DeviceRGB', filter: 'FlateDecode', data: bytes(B64) });
`;
fs.writeFileSync(ROOT + 'src/billing/pdf-brand.js', out);
console.log('pdf-brand: ' + W + '×' + H + ' · ' + data.length + ' B deflated · paper rgb(' + paper.join(', ') + ') · source sha256 ' + sha.slice(0, 12));
