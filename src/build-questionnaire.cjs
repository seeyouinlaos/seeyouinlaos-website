'use strict';
/* THE QUESTIONNAIRE'S BROWSER COPY: src/questionnaire.js is the one source (an ES module the Worker imports); this writes
 * assets/questionnaire.js — the same code as a plain script that hangs the module on window.SIYL_QUESTIONNAIRE.
 *   node src/build-questionnaire.cjs          # write assets/questionnaire.js
 *   node src/build-questionnaire.cjs --check  # exit 1 if the copy is stale */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'src/questionnaire.js'), 'utf8');
const names = [];
const body = src.replace(/^export (const|function) ([A-Za-z_]+)/gm, (m, kind, name) => { names.push(name); return kind + ' ' + name; });
const js = '/* GENERATED by src/build-questionnaire.cjs from src/questionnaire.js — do not edit here. The one questionnaire schema, for the browser. */\n' +
  '(function () {\n\'use strict\';\n' + body + '\nwindow.SIYL_QUESTIONNAIRE = { ' + names.map((n) => n + ': ' + n).join(', ') + ' };\n})();\n';
const dest = path.join(ROOT, 'assets/questionnaire.js');
if (process.argv.includes('--check')) { const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : ''; if (cur !== js) { console.error('QUESTIONNAIRE: assets/questionnaire.js is stale — run node src/build-questionnaire.cjs'); process.exit(1); } console.log('questionnaire: current'); process.exit(0); }
fs.writeFileSync(dest, js);
console.log('questionnaire: ' + names.length + ' exports → assets/questionnaire.js');
