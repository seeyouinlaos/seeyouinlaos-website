'use strict';
/* THE STAY MEDIA RECORD (Owner, release 012 · 19 Sep 2026): src/stay-media.json is the one place that says which
 * photographs stand for a hotel on The Journey and what each shows (the hotel taxonomy: exterior · architecture ·
 * lobby · room · suite · pool · grounds · facilities), with the Owner's Drive folder each came from. This script writes
 * the browser module assets/stay-media.js from it and refuses a record that breaks the rule.
 *   node src/build-stay-media.cjs          # write assets/stay-media.js
 *   node src/build-stay-media.cjs --check  # exit 1 if the module is stale or the record breaks the rule */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const src = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/stay-media.json'), 'utf8'));
const KINDS = src._taxonomy.hotel, LEAD = ['exterior', 'architecture', 'pool', 'grounds', 'lobby'];
const out = {}, problems = [];
for (const key of Object.keys(src)) {
  if (key.startsWith('_')) continue;
  const h = src[key];
  const seen = new Set();
  h.images.forEach((im, i) => {
    if (!KINDS.includes(im.kind)) problems.push(key + ' · ' + im.src + ': kind "' + im.kind + '" is not a hotel kind');
    if (!fs.existsSync(path.join(ROOT, im.src))) problems.push(key + ' · ' + im.src + ' is not on disk');
    if (!im.caption || !im.source) problems.push(key + ' · ' + im.src + ': caption and source are required');
    if (seen.has(im.src)) problems.push(key + ' · ' + im.src + ' twice in one gallery'); seen.add(im.src);
    /* a frame's own focal point (the Media Asset Agent): decided by looking, with its reason */
    if (im.focal !== undefined && (!/^\d{1,3}% \d{1,3}%$/.test(im.focal) || !im.focalWhy)) problems.push(key + ' · ' + im.src + ': a focal point is "x% y%" with its focalWhy');
  });
  /* the lead frame shows the house whenever the Owner's photography has one; a hotel photographed only in its rooms leads with a room */
  const hasHouse = h.images.some((im) => LEAD.includes(im.kind));
  if (h.lead && (!h.leadWhy || h.images[0].kind !== h.lead)) problems.push(key + ': a declared lead needs its reason and must be the first frame');
  if (!h.lead && hasHouse && h.images.length && !LEAD.includes(h.images[0].kind)) problems.push(key + ': the first frame must show the house (' + LEAD.join(', ') + '), not a ' + h.images[0].kind);
  out[key] = { name: h.name, city: h.city, images: h.images.map((im) => Object.assign({ src: im.src, kind: im.kind, caption: im.caption }, im.focal ? { focal: im.focal } : {})) };
}
if (problems.length) { console.error('STAY MEDIA: ' + problems.join('\n')); process.exit(1); }
const js = '/* GENERATED by src/build-stay-media.cjs from src/stay-media.json — do not edit here. The hotel photographs of The Journey:\n' +
  '   one record per hotel, each frame with its kind (the hotel taxonomy) and its caption; the Owner\'s Drive source is in the record. */\n' +
  'window.SIYL_STAY_MEDIA = ' + JSON.stringify(out) + ';\n';
const dest = path.join(ROOT, 'assets/stay-media.js');
if (process.argv.includes('--check')) { const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : ''; if (cur !== js) { console.error('STAY MEDIA: assets/stay-media.js is stale — run node src/build-stay-media.cjs'); process.exit(1); } console.log('STAY MEDIA: current (' + Object.keys(out).length + ' hotels)'); process.exit(0); }
fs.writeFileSync(dest, js);
console.log('stay media: ' + Object.keys(out).length + ' hotels · ' + Object.values(out).reduce((n, h) => n + h.images.length, 0) + ' frames → assets/stay-media.js');
