'use strict';
/* Generates assets/experience-galleries.js from src/experience-galleries.json —
 * the curated, source-traced photograph sets of the Experience places (one
 * numbered Drive folder each). The JSON is the record (Drive file id and
 * original file name per image); the JS is what the pages load. Run after the
 * JSON changes; the test suite fails when the two drift apart.
 *
 * THE MEDIA TAXONOMY (Owner, release 012 · 19 Sep 2026): every frame carries its
 * `kind`; the record's `_taxonomy` says which kinds a restaurant, a café, a bar and
 * an experience may show. A frame of a forbidden kind (food, drink) or of a kind
 * outside the place's category refuses the build — See You In Laos is not a food blog. */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const src = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/experience-galleries.json'), 'utf8'));
const TAX = src._taxonomy;
/* the category of a place follows its roles on the website (assets/experiences.js) */
const rolesOf = {};
for (const m of fs.readFileSync(path.join(ROOT, 'assets/experiences.js'), 'utf8').matchAll(/\{ id: '([a-z0-9-]+)', roles: \[([^\]]*)\]/g)) rolesOf[m[1]] = m[2].replace(/['\s]/g, '').split(',').filter(Boolean);
function categoryOf(id) {
  const r = rolesOf[id] || [];
  if (r.includes('bar')) return 'bar';
  if (r.includes('cafe')) return 'cafe';
  if (r.some((x) => x === 'lunch' || x === 'dinner' || x === 'breakfast')) return 'restaurant';
  return 'experience';
}
const out = {}, problems = [];
for (const id of Object.keys(src)) {
  if (id.startsWith('_')) continue;
  const g = src[id], cat = categoryOf(id), allowed = TAX[cat] || [];
  const seen = new Set();
  g.images.forEach((im, i) => {
    if (!im.kind) problems.push(id + ' · ' + im.src + ': no kind');
    else if (TAX.never.includes(im.kind)) problems.push(id + ' · ' + im.src + ': a ' + im.kind + ' photograph never stands for a place');
    else if (!allowed.includes(im.kind)) problems.push(id + ' · ' + im.src + ': kind "' + im.kind + '" is not a ' + cat + ' kind (' + allowed.join(', ') + ')');
    if (!fs.existsSync(path.join(ROOT, im.src))) problems.push(id + ' · ' + im.src + ' is not on disk');
    if (seen.has(im.src)) problems.push(id + ' · ' + im.src + ' twice'); seen.add(im.src);
    if (!im.drive || !im.file) problems.push(id + ' · ' + im.src + ': no Drive provenance');
    if (i === 0 && (cat === 'restaurant' || cat === 'cafe' || cat === 'bar') && !['interior', 'dining-room', 'counter', 'architecture', 'exterior', 'design'].includes(im.kind)) problems.push(id + ': the lead frame must show the place (interior, dining room, counter, architecture, exterior, design), not ' + im.kind);
  });
  out[id] = { frame: g.frame, images: g.images.map((im) => {
    const o = { src: im.src, w: im.w, h: im.h, alt: im.alt, kind: im.kind };
    if (im.pos) o.pos = im.pos;
    return o;
  }) };
}
if (problems.length) { console.error('EXPERIENCE GALLERIES: ' + problems.join('\n')); process.exit(1); }
const js = '/* generated by src/build-experience-galleries.cjs from src/experience-galleries.json — DO NOT EDIT BY HAND.\n' +
  ' * The curated photograph set of every Experience place: frame ratio, then the\n' +
  ' * images in gallery order (the first is the lead), each with its intrinsic size,\n' +
  ' * alternative text and kind (the media taxonomy — never a dish). Source traceability\n' +
  ' * (Drive file id, original name) is in the JSON and in assets/images/ASSET-MAP.md. */\n' +
  'window.SIYL_EXP_GALLERY = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(ROOT, 'assets/experience-galleries.js'), js);
console.log('experience galleries:', Object.keys(out).length, 'places,', Object.values(out).reduce((n, g) => n + g.images.length, 0), 'photographs');
