'use strict';
/**
 * THE ADMIN CONSOLE PAGE (Owner, 7 Oct 2026). src/admin/billing.html is authored as a page (its asset references stamped
 * by src/asset-versions.cjs like every other page), but it is NOT a public static asset (src/ never is): the Worker serves
 * it at /admin/billing itself, with no-store / noindex / frame-deny headers. This writes the Worker's copy:
 *
 *   node src/build-admin-page.cjs          # write src/admin-page.js from src/admin/billing.html
 *   node src/build-admin-page.cjs --check  # exit 1 when the Worker's copy is not the page
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(__dirname, 'admin', 'billing.html');
const OUT = path.join(__dirname, 'admin-page.js');
const html = fs.readFileSync(SRC, 'utf8');
const body = '/* GENERATED by src/build-admin-page.cjs from src/admin/billing.html — do not edit; edit the page and run the build. */\n' +
  'export default ' + JSON.stringify(html) + ';\n';
if (process.argv.includes('--check')) {
  const ok = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === body;
  console.log(ok ? 'ADMIN PAGE: the Worker\'s copy is current' : 'ADMIN PAGE: src/admin-page.js is stale — run node src/build-admin-page.cjs');
  if (!ok) process.exit(1);
} else {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== body) fs.writeFileSync(OUT, body);
  console.log('admin page: src/admin-page.js ← src/admin/billing.html (' + html.length + ' B)');
}
