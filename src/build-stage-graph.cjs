'use strict';
/* THE STAGE GRAPH'S BROWSER COPY: src/stage-graph.js is the one source (an ES module the Worker imports); this writes
 * assets/stage-graph.js — the same code as a plain script that hangs the module on window.SIYL_GRAPH.
 *   node src/build-stage-graph.cjs          # write assets/stage-graph.js
 *   node src/build-stage-graph.cjs --check  # exit 1 if the copy is stale */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'src/stage-graph.js'), 'utf8');
const names = [];
const body = src.replace(/^export (const|function) ([A-Za-z_]+)/gm, (m, kind, name) => { names.push(name); return kind + ' ' + name; });
const js = '/* GENERATED by src/build-stage-graph.cjs from src/stage-graph.js — do not edit here. The one stage graph, for the browser. */\n' +
  '(function () {\n\'use strict\';\n' + body + '\nwindow.SIYL_GRAPH = { ' + names.map((n) => n + ': ' + n).join(', ') + ' };\n})();\n';
const dest = path.join(ROOT, 'assets/stage-graph.js');
if (process.argv.includes('--check')) { const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : ''; if (cur !== js) { console.error('STAGE GRAPH: assets/stage-graph.js is stale — run node src/build-stage-graph.cjs'); process.exit(1); } console.log('stage graph: current'); process.exit(0); }
fs.writeFileSync(dest, js);
console.log('stage graph: ' + names.length + ' exports → assets/stage-graph.js');
