/* the link annotations of a PDF, read from its bytes: every /Link with a /URI action and its rectangle (points) */
function pdfLinks(buf) {
  const s = Buffer.isBuffer(buf) ? buf.toString('latin1') : String(buf);
  const out = [];
  /* one object at a time (obj … endobj), its dictionary only — a stream's bytes never run into the next object */
  for (const m of s.matchAll(/\d+\s+\d+\s+obj([\s\S]*?)endobj/g)) {
    const o = m[1].split(/\bstream\r?\n/)[0];
    if (!/\/Subtype\s*\/Link\b/.test(o)) continue;
    const uri = (o.match(/\/URI\s*\(([^)]*)\)/) || [])[1];
    const rect = (o.match(/\/Rect\s*\[\s*([-\d.\s]+)\]/) || [])[1];
    if (!uri || !rect) continue;
    const [x1, y1, x2, y2] = rect.trim().split(/\s+/).map(Number);
    out.push({ uri: uri.replace(/\\([()\\])/g, '$1'), rect: [x1, y1, x2, y2], w: Math.abs(x2 - x1), h: Math.abs(y2 - y1) });
  }
  return out;
}
/* the PDF's links against the source: every source URL a link, nothing else linked, every tap area generous enough */
function linkProblems(U, buf) {
  const links = pdfLinks(buf), want = sources(U).map(([, u]) => u), problems = [];
  const count = (arr) => arr.reduce((a, u) => (a[u] = (a[u] || 0) + 1, a), {});
  const have = count(links.map((l) => l.uri)), need = count(want);
  for (const u of Object.keys(need)) if ((have[u] || 0) < need[u]) problems.push('missing link ' + u + ' (' + (have[u] || 0) + ' of ' + need[u] + ')');
  for (const u of Object.keys(have)) if (!need[u]) problems.push('unexpected link ' + u);
  for (const l of links) if (l.h < TAP_MIN || l.w < 60) problems.push('tap area too small for ' + l.uri + ': ' + l.w.toFixed(1) + ' × ' + l.h.toFixed(1) + ' pt');
  return { links, problems };
}

async function playwright() {
  for (const m of [process.env.PLAYWRIGHT_MODULE, 'playwright']) { if (!m) continue; try { return await import(m); } catch (e) { /* next */ } }
  const { execSync } = require('child_process');
  return import(path.join(execSync('npm root -g', { encoding: 'utf8' }).trim(), 'playwright', 'index.mjs'));
}
async function writePdf(U) {
  const pw = await playwright();
  const b = await pw.chromium.launch();
  const p = await b.newPage();
  await p.setContent(magazine(U), { waitUntil: 'networkidle' });
  await p.evaluate(() => document.fonts.ready);
  const buf = await p.pdf({ preferCSSPageSize: true, printBackground: true, displayHeaderFooter: false, tagged: true, outline: false });
  await b.close();
  fs.mkdirSync(path.dirname(PDF), { recursive: true });
  fs.writeFileSync(PDF, buf);
  return buf;
}
function lockNow(U) { return { source: sha(fs.readFileSync(SRC)), pdf: sha(fs.readFileSync(PDF)), links: sources(U).length }; }
function check() {
  const U = load(), problems = [];
  if (!pageCurrent(U)) problems.push('the page block is not the one the source builds (node src/build-unwritten-rules.cjs --page)');
  let lock = null; try { lock = JSON.parse(fs.readFileSync(LOCK, 'utf8')); } catch (e) { problems.push('no lock file (node src/build-unwritten-rules.cjs)'); }
  if (!fs.existsSync(PDF)) problems.push('no PDF at ' + PDF_REL);
  else if (lock) {
    if (lock.source !== sha(fs.readFileSync(SRC))) problems.push('the PDF was built from another version of the guide — rebuild it');
    if (lock.pdf !== sha(fs.readFileSync(PDF))) problems.push('the PDF is not the one the builder wrote');
    problems.push(...linkProblems(U, fs.readFileSync(PDF)).problems);
  }
  return problems;
}

module.exports = { pageBlock, magazine, pdfLinks, linkProblems, sources, check, plain, TAP_MIN, PDF_REL, BEGIN, END };

if (require.main === module) {
  const argv = process.argv.slice(2);
  (async () => {
    if (argv.includes('--check')) { const p = check(); console.log(p.length ? 'UNWRITTEN RULES NOT CURRENT: ' + p.join(' · ') : 'unwritten rules: page and PDF current'); process.exit(p.length ? 1 : 0); }
    const U = load();
    if (!argv.includes('--page')) {
      const buf = await writePdf(U);
      const { links, problems } = linkProblems(U, buf);
      if (problems.length) { console.error('PDF LINKS: ' + problems.join(' · ')); process.exit(1); }
      fs.writeFileSync(LOCK, JSON.stringify(lockNow(U), null, 1) + '\n');
      console.log('pdf: ' + PDF_REL + ' · ' + buf.length + ' bytes · ' + links.length + ' link annotations, smallest tap ' + Math.min(...links.map((l) => l.h)).toFixed(1) + ' pt');
    }
    console.log('page: ' + (writePage(U) ? 'block rewritten' : 'block current'));
  })().catch((e) => { console.error(e); process.exit(1); });
}
