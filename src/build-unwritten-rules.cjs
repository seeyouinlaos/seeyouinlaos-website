/* THE UNWRITTEN RULES — the builder (Owner, 27 Sep 2026). From src/unwritten-rules.js, the ONE source of the guide:
 *   · the page's generated block in unwritten-rules.html (between the UR:BEGIN and UR:END markers)
 *   · the mini-magazine assets/pdf/see-you-in-laos-unwritten-rules.pdf — set by Chromium in the site's own typefaces, every
 *     source URL printed in full and a real link (a PDF URI annotation with a generous tap area)
 *   · src/unwritten-rules.lock.json — the source each was built from, and the PDF's own fingerprint
 *
 *   node src/build-unwritten-rules.cjs           the page block and the PDF (needs Playwright: PLAYWRIGHT_MODULE or global)
 *   node src/build-unwritten-rules.cjs --page    the page block only (no browser)
 *   node src/build-unwritten-rules.cjs --check   exit 1 when the page block, the PDF or its links no longer match the source (gate U1)
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(__dirname, 'unwritten-rules.js');
const PAGE = path.join(ROOT, 'unwritten-rules.html');
const PDF_REL = 'assets/pdf/see-you-in-laos-unwritten-rules.pdf';
const PDF = path.join(ROOT, PDF_REL);
const LOCK = path.join(__dirname, 'unwritten-rules.lock.json');
const BEGIN = '<!-- UR:BEGIN · generated by src/build-unwritten-rules.cjs from src/unwritten-rules.js — do not edit by hand -->';
const END = '<!-- UR:END -->';

const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
const load = () => { delete require.cache[require.resolve(SRC)]; return require(SRC); };
const esc = (t) => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
/* the prose carries one markup only, <em> — everything else is text */
const H = (t) => String(t).split(/(<\/?em>)/).map((p) => (/^<\/?em>$/.test(p) ? p : esc(p))).join('');
const plain = (t) => String(t).replace(/<\/?em>/g, '');
const pad = (n) => String(n).padStart(2, '0');

/* every source a guest can open: [label, url] in reading order */
function sources(U) { return [...U.intro.sources, ...U.rules.flatMap((r) => r.sources), ...(U.closing.sources || [])]; }

/* ---------------------------------------------------------------- the page block */
function srcHtml(list) {
  if (!list.length) return '';
  return '<div class="ur-src"><p class="ur-src-h">Sources &amp; Further Reading</p><ul class="ur-src-l" lang="en" data-i18n-skip>' +
    list.map(([l, u]) => '<li><a href="' + esc(u) + '" target="_blank" rel="noopener noreferrer"><span class="ur-src-t">' + esc(l) + '</span><span class="ur-src-u">' + esc(u) + '</span></a></li>').join('') +
    '</ul></div>';
}
function blocksHtml(blocks, where) {
  const qs = blocks.filter((b) => b[0] === 'q').length; let qi = 0;
  return blocks.map((b) => {
    if (b[0] === 'p') return '<p>' + H(b[1]) + '</p>';
    if (b[0] === 'h') return '<h3 class="ur-h3">' + H(b[1]) + '</h3>';
    if (b[0] === 'l') return '<ul class="ur-lines">' + b[1].map((x) => '<li>' + H(x) + '</li>').join('') + '</ul>';
    /* a statement set apart: in the closing, the first is the rule itself, the last the reason everyone is there */
    const i = qi++; const cls = where === 'closing' ? (i === 0 ? 'ur-be' : i === qs - 1 ? 'ur-end' : 'ur-q ur-q-c') : 'ur-q';
    return '<p class="' + cls + '">' + H(b[1]) + '</p>';
  }).join('\n');
}
function pageBlock(U) {
  const rules = U.rules.map((r) => '<article class="ur-rule" id="rule-' + r.n + '" aria-labelledby="rule-' + r.n + '-h">\n' +
    '<h2 class="ur-rh" id="rule-' + r.n + '-h"><span class="ur-no">' + r.n + '<span class="ur-dot" aria-hidden="true">.</span></span> <span class="ur-rt">' + H(r.title) + '</span></h2>\n' +
    '<div class="ur-body">\n' + blocksHtml(r.blocks, 'rule') + '\n</div>\n' + srcHtml(r.sources) + '\n</article>').join('\n');
  return [
    BEGIN,
    '<header class="ur-head">',
    '<h1 class="ur-title">' + H(U.title) + '</h1>',
    '<p class="ur-sub">' + H(U.subtitle) + '</p>',
    '<p class="ur-kicker">' + H(U.kicker) + '</p>',
    '</header>',
    '<div class="ur-lead" data-private>',
    '<p class="ur-gate" data-ur-gate hidden>Before you continue, please read the Unwritten Rules. Your confirmation is at the end of the guide.</p>',
    '<div class="ur-actions"><a class="p-act quiet ur-dl" href="' + PDF_REL + '?v=' + pdfTag() + '" download="see-you-in-laos-unwritten-rules.pdf" type="application/pdf" data-ur-download>Download · Unwritten Rules</a><p class="ur-dl-note">A PDF edition, in English.</p></div>',
    '</div>',
    '<div class="ur-guide" data-private>',
    '<section class="ur-intro" aria-label="Introduction"><div class="ur-body">\n' + blocksHtml(U.intro.blocks, 'intro') + '\n</div>\n' + srcHtml(U.intro.sources) + '\n</section>',
    '<nav class="ur-index" aria-label="The Twenty Rules"><p class="ur-index-h">The Twenty Rules</p><ol>' +
      U.rules.map((r) => '<li><a href="#rule-' + r.n + '"><span class="ur-in">' + r.n + '</span><span class="ur-it">' + H(r.title) + '</span></a></li>').join('') + '</ol></nav>',
    rules,
    '<section class="ur-close" aria-labelledby="ur-close-h">\n<h2 class="ur-ch" id="ur-close-h">' + H(U.closing.title) + '</h2>\n' + blocksHtml(U.closing.blocks, 'closing') + '\n</section>',
    '</div>',
    END
  ].join('\n');
}
function pdfTag() { try { return sha(fs.readFileSync(PDF)).slice(0, 8); } catch (e) { return 'none'; } }
function writePage(U) {
  const html = fs.readFileSync(PAGE, 'utf8');
  const a = html.indexOf(BEGIN), b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('unwritten-rules.html: the UR markers are missing');
  const out = html.slice(0, a) + pageBlock(U) + html.slice(b + END.length);
  if (out !== html) fs.writeFileSync(PAGE, out);
  return out !== html;
}
function pageCurrent(U) {
  const html = fs.readFileSync(PAGE, 'utf8'); const a = html.indexOf(BEGIN), b = html.indexOf(END);
  return a >= 0 && b > a && html.slice(a, b + END.length) === pageBlock(U);
}

